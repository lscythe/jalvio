package dev.lscythe.app.jalvio.core.testing

import kotlinx.cinterop.ExperimentalForeignApi
import platform.Foundation.NSBundle
import platform.Foundation.NSString
import platform.Foundation.NSUTF8StringEncoding
import platform.Foundation.stringWithContentsOfFile

@OptIn(ExperimentalForeignApi::class)
actual fun readResource(path: String): String {
    val resourceDirectory =
        checkNotNull(NSBundle.mainBundle.resourcePath) { "Missing bundle resource directory" }
    return checkNotNull(
        NSString.stringWithContentsOfFile(
            path = "$resourceDirectory/$path",
            encoding = NSUTF8StringEncoding,
            error = null,
        )
    ) {
        "Missing test resource: $path"
    }
}
